#!/usr/bin/env node
// Turns the native QR scanner's shared centre-pick examples into Swift + Java test cases.
//   node scripts/gen-qr-pick-cases.mjs          → writes the two files
//   node scripts/gen-qr-pick-cases.mjs --check  → exits 1 when a committed file is out of date
// src/lib/__tests__/qrCentrePick.test.ts runs the same check in CI.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const EXAMPLES = resolve(root, "src/lib/__tests__/fixtures/qrCentrePick.examples.json");
export const SWIFT_OUT = resolve(root, "mobile/ios/App/AppTests/QrCentrePickCases.swift");
export const JAVA_OUT = resolve(root, "mobile/android/app/src/test/java/com/sellerflow/live/QrCentrePickCases.java");

const HEADER = "GENERATED by scripts/gen-qr-pick-cases.mjs from src/lib/__tests__/fixtures/qrCentrePick.examples.json — do not edit by hand.";
const str = (s) => JSON.stringify(String(s)); // a valid Swift and Java string literal for these texts
const num = (n) => (Number.isInteger(n) ? `${n}.0` : String(n));

export function swiftCases(ex) {
  const pick = ex.pick.map((c) => {
    const hits = c.hits.map((h) => `QrCentrePick.Hit(text: ${str(h.text)}, cx: ${num(h.cx)}, cy: ${num(h.cy)})`).join(", ");
    return `        PickCase(id: ${str(c.id)}, frameCx: ${num(c.frame.cx)}, frameCy: ${num(c.frame.cy)}, side: ${num(c.frame.side)}, hits: [${hits}], expect: ${str(c.expect)}),`;
  });
  const streak = ex.streak.map((c) => `        StreakCase(id: ${str(c.id)}, steps: [${c.steps.map(str).join(", ")}], expect: [${c.expect.map(str).join(", ")}]),`);
  return [
    `// ${HEADER}`,
    "",
    "@testable import App",
    "",
    "struct PickCase { let id: String; let frameCx: Double; let frameCy: Double; let side: Double; let hits: [QrCentrePick.Hit]; let expect: String }",
    "struct StreakCase { let id: String; let steps: [String]; let expect: [String] }",
    "",
    "enum QrCentrePickCases {",
    `    static let margin: Double = ${num(ex.margin)}`,
    `    static let frames: Int = ${ex.frames}`,
    "    static let pick: [PickCase] = [",
    ...pick,
    "    ]",
    "    static let streak: [StreakCase] = [",
    ...streak,
    "    ]",
    "}",
    "",
  ].join("\n");
}

export function javaCases(ex) {
  const pick = ex.pick.map((c) => {
    const hits = c.hits.map((h) => `new QrCentrePick.Hit(${str(h.text)}, ${num(h.cx)}, ${num(h.cy)})`).join(", ");
    return `        new PickCase(${str(c.id)}, ${num(c.frame.cx)}, ${num(c.frame.cy)}, ${num(c.frame.side)}, new QrCentrePick.Hit[] { ${hits} }, ${str(c.expect)}),`;
  });
  const streak = ex.streak.map((c) => `        new StreakCase(${str(c.id)}, new String[] { ${c.steps.map(str).join(", ")} }, new String[] { ${c.expect.map(str).join(", ")} }),`);
  return [
    `// ${HEADER}`,
    "package com.sellerflow.live;",
    "",
    "final class QrCentrePickCases {",
    `    static final double MARGIN = ${num(ex.margin)};`,
    `    static final int FRAMES = ${ex.frames};`,
    "",
    "    static final class PickCase {",
    "        final String id; final double frameCx; final double frameCy; final double side; final QrCentrePick.Hit[] hits; final String expect;",
    "        PickCase(String id, double frameCx, double frameCy, double side, QrCentrePick.Hit[] hits, String expect) {",
    "            this.id = id; this.frameCx = frameCx; this.frameCy = frameCy; this.side = side; this.hits = hits; this.expect = expect;",
    "        }",
    "    }",
    "",
    "    static final class StreakCase {",
    "        final String id; final String[] steps; final String[] expect;",
    "        StreakCase(String id, String[] steps, String[] expect) { this.id = id; this.steps = steps; this.expect = expect; }",
    "    }",
    "",
    "    static final PickCase[] PICK = {",
    ...pick,
    "    };",
    "",
    "    static final StreakCase[] STREAK = {",
    ...streak,
    "    };",
    "",
    "    private QrCentrePickCases() {}",
    "}",
    "",
  ].join("\n");
}

export function generated() {
  const ex = JSON.parse(readFileSync(EXAMPLES, "utf8"));
  return { swift: swiftCases(ex), java: javaCases(ex) };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const g = generated();
  if (process.argv.includes("--check")) {
    const bad = [[SWIFT_OUT, g.swift], [JAVA_OUT, g.java]].filter(([f, want]) => {
      try { return readFileSync(f, "utf8") !== want; } catch { return true; }
    });
    for (const [f] of bad) console.error(`out of date: ${f}`);
    process.exit(bad.length ? 1 : 0);
  }
  writeFileSync(SWIFT_OUT, g.swift);
  writeFileSync(JAVA_OUT, g.java);
  console.log("wrote", SWIFT_OUT, "and", JAVA_OUT);
}
