// DEV/BUILD-TIME ONLY — generates the "Sans" vector outlines used by the one-sticker engine
// (src/redesign/adapters/oneSticker*.ts). NOT shipped as a font: only its OUTPUT (a committed
// .ts module, loaded lazily) ships. The runtime rasterizes these outlines itself (pure TS,
// nonzero scanline at pixel centres) → the SAME bits on iPhone, Android, laptop and in tests.
//
// Inputs (static instances cut from the bundled variable fonts in server/fonts/, OFL):
//   python -m fontTools.varLib.instancer server/fonts/NotoSans.ttf wght=400 wdth=100 -o ns400.ttf
//   (and 700, 900), then subset to the Latin/Greek/Cyrillic/Vietnamese/punctuation set:
//   python -m fontTools.subset ns400.ttf --unicodes="$LAT" --output-file=nsl400.ttf --no-hinting
//   python -m fontTools.varLib.instancer server/fonts/NotoSansTC.ttf wght=400 -o tc400.ttf
//   python -m fontTools.subset tc400.ttf --unicodes="$CJKX" --output-file=tcx400.ttf --no-hinting
//   LAT  = U+0020-007E,U+00A0-017F,U+01A0-01B0,U+01CD-01DC,U+0218-021B,U+0300-036F,U+0400-04FF,
//          U+1E00-1EFF,U+2010-2027,U+2030-203A,U+20A0-20BF,U+2103,U+2116,U+2122,U+2190-2193,U+2212
//          (ASCII, Latin-1, Ext-A, Vietnamese ơ ư + Ext Additional, pinyin, Romanian, Cyrillic,
//          punctuation, currency). Anything else is drawn by the fallback (system font).
//   CJKX = U+3000-303F,U+3040-30FF,U+31F0-31FF,U+FF00-FFEF   (kana, CJK punctuation, full-width
//          and half-width forms — the parts the CJK ideograph atlas does not have)
//
//   node scripts/gen-sans-outlines.mjs <dir with nsl400/700/900.ttf + tcx400.ttf>
//
// Output (one lazy chunk each): src/redesign/adapters/sansOutlines.{400,700,900,cjkx}.ts
//   SANS_FACE = { upm, asc, desc, g: { [cp]: "adv|path" } }. path = M/L/Q/C/Z with RELATIVE
//   integer font units (each pair is a delta from the previous point; y DOWN, the first M is
//   relative to the pen on the baseline). Decoded by oneStickerFonts.ts parseOutline().
import opentype from "opentype.js";
import fs from "node:fs";
import path from "node:path";

const DIR = process.argv[2];
if (!DIR) { console.error("usage: node scripts/gen-sans-outlines.mjs <font dir>"); process.exit(1); }

function face(file) {
  const font = opentype.loadSync(path.join(DIR, file));
  const upm = font.unitsPerEm;
  const g = {};
  const cmap = font.tables.cmap.glyphIndexMap;
  for (const key of Object.keys(cmap).map(Number).sort((a, b) => a - b)) {
    const glyph = font.glyphs.get(cmap[key]);
    const p = glyph.getPath(0, 0, upm); // fontSize = upm → coordinates in font units, y down
    let s = "";
    const r = (v) => Math.round(v);
    let px = 0, py = 0;
    const d = (x, y) => { const a = r(x) - px, b = r(y) - py; return `${a} ${b}`; };
    for (const c of p.commands) {
      if (c.type === "M" || c.type === "L") { s += `${c.type}${d(c.x, c.y)}`; px = r(c.x); py = r(c.y); }
      else if (c.type === "Q") { s += `Q${d(c.x1, c.y1)} ${d(c.x, c.y)}`; px = r(c.x); py = r(c.y); }
      else if (c.type === "C") { s += `C${d(c.x1, c.y1)} ${d(c.x2, c.y2)} ${d(c.x, c.y)}`; px = r(c.x); py = r(c.y); }
      else if (c.type === "Z") s += "Z";
    }
    g[key] = `${r(glyph.advanceWidth ?? upm)}|${s}`;
  }
  return { upm, asc: font.ascender, desc: font.descender, g };
}

const write = (name, f, what) => {
  const body = `// AUTO-GENERATED by scripts/gen-sans-outlines.mjs — DO NOT EDIT BY HAND.
// "Sans" outlines for the one-sticker engine: ${what}. SIL Open Font License 1.1
// (server/fonts/OFL.txt). Loaded lazily by oneStickerFonts.ts.
import type { SansFace } from "./oneStickerFonts";
export const SANS_FACE: SansFace = ${JSON.stringify(f)};
`;
  fs.writeFileSync(`src/redesign/adapters/sansOutlines.${name}.ts`, body);
  console.log(`wrote sansOutlines.${name}.ts`, (body.length / 1024).toFixed(0), "KB,", Object.keys(f.g).length, "glyphs");
};
for (const w of ["400", "700", "900"]) write(w, face(`nsl${w}.ttf`), `Noto Sans ${w} (Latin, Cyrillic, Vietnamese, punctuation)`);
write("cjkx", face("tcx400.ttf"), "Noto Sans TC 400 (kana, CJK punctuation, full-width and half-width forms)");
