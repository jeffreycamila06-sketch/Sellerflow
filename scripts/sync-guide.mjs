// Turns docs/support/sfl-guide.md into sql/116b_guide_seed.sql — an idempotent upsert of the
// support_guide table (sql/116). Run after every guide change, commit the SQL, and apply it
// after the merge (no Render deploy needed: the server re-reads the table every 5 minutes).
//   node scripts/sync-guide.mjs
// Same guide file → byte-identical SQL. Sections removed from the file are deleted.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { parseGuide } from "../server/helpBot.js";

const lit = (v) => (v === null ? "null" : `'${String(v).replace(/'/g, "''")}'`);

export function buildGuideSql(md) {
  const sections = parseGuide(md);
  if (!sections.length) throw new Error("guide has no sections — refusing to empty support_guide");
  const ids = new Set();
  for (const s of sections) {
    if (ids.has(s.id)) throw new Error(`duplicate section id: ${s.id}`);
    ids.add(s.id);
  }
  const rows = sections.map((s) => {
    const checked = /^\d{4}-\d{2}-\d{2}$/.test(s.checked) ? `${lit(s.checked)}::date` : "null";
    return `  (${lit(s.id)}, ${lit(s.title)}, ${checked}, ${lit(s.keywords)}, ${lit(s.body)})`;
  });
  return [
    "-- ============================================================================",
    "-- sql/116b — support_guide seed. GENERATED by scripts/sync-guide.mjs from",
    "-- docs/support/sfl-guide.md — do not edit by hand. Needs sql/116 first.",
    "-- Idempotent: unchanged sections are not touched; a changed \"Last checked\" date marks the",
    "-- linked FAQ entries needs_recheck (trigger); sections no longer in the file are deleted.",
    "-- ============================================================================",
    "begin;",
    "insert into public.support_guide (id, title, checked, keywords, body) values",
    rows.join(",\n"),
    "on conflict (id) do update set",
    "  title = excluded.title, checked = excluded.checked, keywords = excluded.keywords,",
    "  body = excluded.body, updated_at = now()",
    "where (support_guide.title, support_guide.checked, support_guide.keywords, support_guide.body)",
    "  is distinct from (excluded.title, excluded.checked, excluded.keywords, excluded.body);",
    `delete from public.support_guide where id not in (${sections.map((s) => lit(s.id)).join(", ")});`,
    "commit;",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = new URL("../", import.meta.url);
  const sql = buildGuideSql(readFileSync(new URL("docs/support/sfl-guide.md", root), "utf8"));
  writeFileSync(new URL("sql/116b_guide_seed.sql", root), sql);
  console.log(`sql/116b_guide_seed.sql written (${sql.length} bytes)`);
}
