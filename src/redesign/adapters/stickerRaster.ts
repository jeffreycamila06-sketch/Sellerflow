const SCRIPT_ASCII = 1, SCRIPT_CJK = 2, SCRIPT_UNSUPPORTED = 3;
const ATOMIC_LATIN: Record<string, string> = {
  "đ": "d", "Đ": "D", "ł": "l", "Ł": "L", "ø": "o", "Ø": "O", "æ": "ae", "Æ": "AE",
  "œ": "oe", "Œ": "OE", "ß": "ss", "þ": "th", "Þ": "Th", "ð": "d", "Ð": "D", "ı": "i",
};
function transliterateLatin(s: string): string {
  if (!s) return "";
  let out = "";
  for (const ch of s.normalize("NFD")) {
    const cp = ch.codePointAt(0) ?? 0;
    if (cp >= 0x300 && cp <= 0x36f) continue;
    out += ATOMIC_LATIN[ch] ?? ch;
  }
  return out;
}
function isCjkIdeograph(cp: number): boolean {
  return (cp >= 0x4e00 && cp <= 0x9fff) || (cp >= 0x3400 && cp <= 0x4dbf) || (cp >= 0xf900 && cp <= 0xfaff);
}
function classifyScript(s: string): number {
  let hasCjk = false;
  for (const ch of s) {
    const cp = ch.codePointAt(0) ?? 0;
    if (cp <= 127) continue;
    if (isCjkIdeograph(cp)) { hasCjk = true; continue; }
    return SCRIPT_UNSUPPORTED;
  }
  return hasCjk ? SCRIPT_CJK : SCRIPT_ASCII;
}
function stripUnrenderable(s: string): string {
  let out = "";
  for (const ch of s) { const cp = ch.codePointAt(0) ?? 0; if (cp <= 127 || isCjkIdeograph(cp)) out += ch; }
  return out;
}

// ── Script modes ─────────────────────────────────────────────────────────────
// "legacy"   — the TEXT path's narrowing, verbatim (transliterate Latin
//              diacritics to ASCII, strip everything not ASCII/CJK). Used by
//              emitTextTspl so the layout parity vs the frozen reference stays
//              byte-exact; also what Classic text mode actually prints.
// "extended" — the BITMAP path's narrowing: keep any char the atlases cover.
//              The Latin atlas now spans ASCII + Latin-1 + Ext-A/B + Ext
//              Additional (full Vietnamese incl. tone marks; Indonesian/
//              Filipino/European), so "Nguyễn Thị Hằng" prints WITH diacritics
//              instead of the legacy "Nguyen Thi Hang". Geometry is unchanged
//              (same cell advance per char), only the glyphs differ. Scripts
//              with no atlas (Thai/Arabic/Korean/…) keep the legacy fallback
//              (handle / Buyer #N) — never tofu.
export type ScriptMode = "legacy" | "extended";
// `extraAtlas` = the Cyrillic atlas is in hand (RasterAtlases.cyrillic — glyphAtlas.cyrillic.ts, a
// separate file so the Latin atlas and its goldens never change): Cyrillic (U+0400–04FF) and
// "…" then join the atlas-covered tier — a Bulgarian/Russian name prints from that atlas on the
// same cell geometry instead of falling back to the handle. Only the generic-printer / Niimbot
// IMAGE paths pass that atlas; the D520BT stream never does, so its bytes stay byte-identical
// to main (stickerSpacing.offPins pins all 360 labels).
const isAtlasLatin = (cp: number, extra = false): boolean =>
  (cp >= 0xa1 && cp <= 0xff) || (cp >= 0x100 && cp <= 0x24f) || (cp >= 0x1e00 && cp <= 0x1eff) || (extra && ((cp >= 0x400 && cp <= 0x4ff) || cp === 0x2026));
function stripUnrenderableExt(s: string, extra = false): string {
  let out = "";
  for (const ch of s) { const cp = ch.codePointAt(0) ?? 0; if (cp <= 127 || isCjkIdeograph(cp) || isAtlasLatin(cp, extra)) out += ch; }
  return out;
}
// Extended classification: atlas-covered Latin counts as the ASCII tier (same
// font/cell/reflow as ASCII — only the painted glyph differs).
function classifyScriptExt(s: string, extra = false): number {
  let hasCjk = false;
  for (const ch of s) {
    const cp = ch.codePointAt(0) ?? 0;
    if (cp <= 127 || isAtlasLatin(cp, extra)) continue;
    if (isCjkIdeograph(cp)) { hasCjk = true; continue; }
    return SCRIPT_UNSUPPORTED;
  }
  return hasCjk ? SCRIPT_CJK : SCRIPT_ASCII;
}
const hasCjkChar = (s: string): boolean => { for (const ch of s) if (isCjkIdeograph(ch.codePointAt(0) ?? 0)) return true; return false; };

// Does this sticker payload contain ANY CJK ideograph (name/handle/store/items)?
// Gates the dynamic CJK-atlas load: ASCII/Latin prints never wait on the chunk.
export function payloadNeedsCjk(payload: RasterPayload): boolean {
  const b = payload.buyer ?? {};
  if (hasCjkChar(payload.storeName ?? "") || hasCjkChar(b.name ?? "") || hasCjkChar(b.handle ?? "")) return true;
  for (const o of b.orders ?? []) if (hasCjkChar(o.item ?? "") || hasCjkChar(o.time ?? "")) return true;
  return false;
}
// Per-character fallback for a glyph missing from an atlas: ATOMIC map first
// (đ→d …), else the NFD base letter (ễ→e). Returns null when the char has no
// simpler form (the paint loop then keeps the advance — never misaligns).
export function translitCp(cp: number): number | null {
  const ch = String.fromCodePoint(cp);
  const mapped = ATOMIC_LATIN[ch];
  if (mapped) return mapped.codePointAt(0) ?? null;
  const base = ch.normalize("NFD")[0];
  const b = base ? base.codePointAt(0) ?? null : null;
  return b != null && b !== cp ? b : null;
}

