// Bitmap sticker path — shared TS rasterizer (Phase 1, Android dev-verify).
//
// WHY: the new-board D520BT (fw V1.1.7) DOUBLES every ROM font glyph, so the TEXT
// path (TsplBuilder.java / Swift buildTsplSticker / tsplReference.ts) prints garbled
// on those units. Both boards print a TSPL BITMAP raster block CLEAN. So we render
// the WHOLE sticker to a 1-bit raster in TS and send it via BITMAP — clean on the
// new board, identical layout to the old TEXT sticker.
//
// ARCHITECTURE (parity by construction):
//   stickerDrawOps()          — the LAYOUT, mirrored op-for-op from the frozen
//                               tsplReference.ts. THE single source of positions.
//   emitTextTspl(ops)         — serializes ops back into the exact TEXT/BAR stream.
//                               TEST-ONLY: proves emitTextTspl == the frozen
//                               reference byte-for-byte (layout fidelity guard).
//   rasterizeToBitmapTspl()   — the PRODUCTION path: ops → 1-bit buffer (glyph
//                               blit) → ink-band crop → BITMAP blocks → TSPL.
//
// The frozen TEXT builders/goldens are NEVER imported or modified here; the layout
// is re-derived and pinned by the parity test.
//
// Glyphs come from committed 1-bit atlases (glyphAtlas.latin.ts + glyphAtlas.cjk.ts,
// generated by scripts/gen-glyph-atlas.mjs). Runtime never rasterizes a font →
// deterministic goldens. Cells match the printer's built-in font boxes:
//   font "2" 12x20 · "3" 16x24 · "4" 24x32 · CJK "TSS24" 24x24.

