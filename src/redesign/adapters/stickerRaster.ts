// ── Band emission mode (H1 field finding, 2026-09-07) ────────────────────────
// The new-board firmware DOUBLES/ghosts glyphs when BITMAP blocks land at
// arbitrary x offsets (the horizontal ink-extent crop produced x=13-style
// origins; the firmware appears to mis-shift x%8 sub-byte composition — the
// same visual signature as its ROM-font doubling). DEFAULT is therefore
// FULL-WIDTH bands: every BITMAP block at x=0 spanning the whole label width
// (wDots is a multiple of 8 on all five sizes → rowBytes exact, no sub-byte
// shifting for the firmware to get wrong), cropped VERTICALLY only. Payload
// roughly doubles vs horizontal crop but stays far under the naive full
// raster. `horizontalCrop: true` re-enables the old tighter crop — kept for
// the probe triad; flip the default only if the probe proves arbitrary-x safe.
export interface BandOptions { horizontalCrop?: boolean }

// Full uncropped 1-bit raster (bit 1 = ink) — exported so the band-crop lossless
// invariant test can recompose the emitted BITMAP blocks against it.
export interface FullRaster { buf: Uint8Array; w: number; h: number; rowBytes: number }
export function renderStickerBitmap(payload: RasterPayload, wMm: number, hMm: number, atlases: RasterAtlases, mode: ScriptMode = "extended"): FullRaster {
  if (atlases.proportional && mode !== "legacy" && isPropCompactSize(wMm, hMm)) { // font C, image paths only
    const bmp = renderPropCompact(payload, wMm, hMm, atlases);
    return { buf: bmp.buf, w: bmp.w, h: bmp.h, rowBytes: bmp.rowBytes };
  }
  // Compute the QR placement ONCE (legacy/parity mode never has a QR) → the layout wraps
  // the comment before it AND the stamp renders it, from the SAME footprint.
  const cfg = stickerConfig(wMm, hMm);
  const qr = mode === "legacy" ? null : stickerQrPlacement(payload, cfg.wDots, hMm * 8, hMm);
  const { ops, wDots, hDots } = stickerDrawOps(payload, wMm, hMm, mode, qr, !!atlases.cyrillic);
  const bmp = new Bitmap(wDots, hDots);
  paint(bmp, ops, atlases);
  stampHandleQr(bmp, qr); // BITMAP-ONLY (emitTextTspl/native builders never see it)
  return { buf: bmp.buf, w: bmp.w, h: bmp.h, rowBytes: bmp.rowBytes };
}

// ── Buyer TikTok-profile QR (bitmap path only) ───────────────────────────────
// The handle is purged from the free-tier DB, so it rides the printed label. ONE QR
// serves two roles: SFL Parcel Scan reads the @username back off it, AND a plain phone
// camera opens the buyer's TikTok profile (details staff message the receipt). Payload =
// https://tiktok.com/@<handle> (the shortest URL cameras + TikTok both accept). ECC M
// (not Q) keeps a typical ≤37-byte URL at QR v3 (29 modules). Stamped bottom-right; a
// CLEARED footprint guarantees the 4-module quiet zone. 4 dots/module (≈14.5 mm symbol at
// 203 dpi). AVAILABLE ONLY on labels ≥50 mm tall (70×50 / 80×50 / 80×60 / 100×60) — 60×40
// is EXCLUDED entirely (field-tested: an ~11 mm QR scanned too slowly on iPhone 12–15 and
// Android). TEXT-path prints (old binaries / Classic mode) never call this → they carry no
// QR. Gated on the same @username print toggle + a non-blank handle.
export const QR_MODULE_DOTS = 4;
export const QR_QUIET_MODULES = 4;
export const QR_EDGE_MARGIN_DOTS = 8;
export const QR_TEXT_KEEPOUT_GAP = 8; // horizontal buffer between wrapped comment text and the QR block
export const MAX_COMMENT_LINES = 4;   // hard cap on the wrapped order-comment (then ellipsise)
// 60×40 (the only ≤40 mm-tall label) prints no QR at all — every larger size gets one.
export function stickerQrSupported(hMm: number): boolean { return hMm > 40; }

// The QR block placement for this label, or null when no QR will print. SINGLE SOURCE
// for both the layout keep-out (stickerDrawOps wraps the comment before x0) and the
// stamping (stampHandleQr). Same gates as before: size ≥50mm, toggle on, @username
// on, non-blank handle.
export interface QrPlacement { matrix: boolean[][]; x0: number; y0: number; foot: number; scale: number }
export function stickerQrPlacement(payload: RasterPayload, wDots: number, hDots: number, hMm: number): QrPlacement | null {
  const compact = wDots === W50 && hMm === 30;                               // the 50×30 layout: QR on the right, label-tall
  if (!stickerQrSupported(hMm) && !compact) return null;                      // 60×40 → never a QR
  if (!payload.settings || payload.settings.printStickerQr !== true) return null; // toggle DEFAULT OFF
  if (payload.settings.printBuyerUsername === false) return null;             // follows the @username toggle
  const handle = payload.buyer?.handle ? String(payload.buyer.handle).trim() : "";
  if (!handle) return null;                                                   // blank → no QR
  const url = tiktokProfileUrl(handle);
  if (!url) return null;
  const m = qrMatrix(url, "M"); // ECC M keeps the ≤37-byte URL at QR v3 (29 modules)
  if (!m) return null;
  if (compact) {
    // as tall as the label allows: 5 dots/module (≈18 mm symbol), else 4; centred vertically.
    // The symbol ends 8 dots before the raster's right edge — its right quiet zone is those
    // 8 dots + the label's own unprinted 2 mm (384 of 400 dots are printed), so the text
    // column keeps 187 dots instead of losing 20 to white on the right.
    let scale = QR_MODULE_DOTS_50;
    let foot = (m.length + QR_QUIET_MODULES * 2) * scale;
    if (foot > H50 - 2 * QR_EDGE_MARGIN_DOTS) { scale = QR_MODULE_DOTS; foot = (m.length + QR_QUIET_MODULES * 2) * scale; }
    if (foot > H50) return null;
    const x0 = Math.max(0, wDots - (m.length + QR_QUIET_MODULES) * scale - QR_EDGE_MARGIN_DOTS);
    return { matrix: m, x0, y0: Math.max(0, Math.floor((H50 - foot) / 2)), foot, scale };
  }
  const foot = (m.length + QR_QUIET_MODULES * 2) * QR_MODULE_DOTS;
  let x0 = wDots - foot - QR_EDGE_MARGIN_DOTS; if (x0 < 0) x0 = 0;
  let y0 = hDots - foot - QR_EDGE_MARGIN_DOTS; if (y0 < 0) y0 = 0;
  return { matrix: m, x0, y0, foot, scale: QR_MODULE_DOTS };
}
function stampHandleQr(bmp: Bitmap, qr: QrPlacement | null): void {
  if (!qr) return;
  const { matrix: m, x0, y0, foot, scale } = qr;
  bmp.clearRect(x0, y0, Math.min(foot, bmp.w - x0), Math.min(foot, bmp.h - y0)); // quiet zone + clean modules
  const ox = x0 + QR_QUIET_MODULES * scale, oy = y0 + QR_QUIET_MODULES * scale;
  const n = m.length;
  for (let r = 0; r < n; r++) for (let c = 0; c < n; c++) if (m[r][c]) bmp.fillRect(ox + c * scale, oy + r * scale, scale, scale);
}

// PRODUCTION path: payload → 1-bit raster → vertical ink-band crop → full-width
// x=0 BITMAP blocks → TSPL. See BandOptions for why full-width is the default.
export function rasterizeToBitmapTspl(payload: RasterPayload, wMm: number, hMm: number, atlases: RasterAtlases, opts: BandOptions = {}): BitmapTsplResult {
  const cfg = stickerConfig(wMm, hMm);
  let bmp: Bitmap;
  if (atlases.proportional && isPropCompactSize(wMm, hMm)) {
    bmp = renderPropCompact(payload, wMm, hMm, atlases); // font C, image paths only (== renderStickerBitmap)
  } else {
    const qr = stickerQrPlacement(payload, cfg.wDots, hMm * 8, hMm); // this path is always extended/production
    const { ops, wDots, hDots } = stickerDrawOps(payload, wMm, hMm, "extended", qr, !!atlases.cyrillic);
    bmp = new Bitmap(wDots, hDots);
    paint(bmp, ops, atlases);
    stampHandleQr(bmp, qr); // keep the band path == renderStickerBitmap (LOSSLESS invariant)
  }
  const wDots = bmp.w, hDots = bmp.h;

  const out: number[] = [];
  const line = (s: string) => { out.push(...asciiBytes(s), ...CRLF); };
  line(`SIZE ${wMm} mm, ${hMm} mm`);
  line("GAP 2 mm, 0");
  line("DIRECTION 1");
  line("REFERENCE 0,0");
  line("DENSITY 8");
  line("CLS");

  // Vertical ink-band crop: maximal runs of inked rows → one BITMAP each. Runs
  // separated by ≤GAP_MERGE_ROWS blank rows merge into one block (fewer BITMAP
  // commands for the firmware to parse; the few white rows cost ~rowBytes each).
  const GAP_MERGE_ROWS = 4;
  interface Band { y0: number; y1: number }
  const runs: Band[] = [];
  let y = 0;
  while (y < hDots) {
    if (!bmp.rowHasInk(y)) { y++; continue; }
    let y1 = y + 1;
    while (y1 < hDots && bmp.rowHasInk(y1)) y1++;
    const prev = runs[runs.length - 1];
    if (prev && y - prev.y1 <= GAP_MERGE_ROWS) prev.y1 = y1;
    else runs.push({ y0: y, y1 });
    y = y1;
  }

  let bands = 0, inkBytes = 0;
  for (const run of runs) {
    // Full-width default: x0=0, band spans the whole label (wDots % 8 === 0 on
    // every size → rowBytes exact). horizontalCrop keeps the old tight crop.
    let x0 = 0, x1 = wDots;
    if (opts.horizontalCrop) {
      const ext = bmp.inkExtent(run.y0, run.y1);
      if (!ext) continue;
      [x0, x1] = ext;
    }
    const bandW = x1 - x0, bandH = run.y1 - run.y0;
    const rowBytes = (bandW + 7) >> 3;
    const data = new Uint8Array(rowBytes * bandH);
    // Default every bit to WHITE, then stamp ink dots per polarity.
    if (!INK_IS_ZERO) { /* ink=1: buffer already 0 (white); set ink bits below */ }
    else data.fill(0xff); // ink=0: start all-white(1), clear ink bits to 0
    for (let ry = 0; ry < bandH; ry++) for (let rx = 0; rx < bandW; rx++) {
      const ink = (bmp.buf[(run.y0 + ry) * bmp.rowBytes + ((x0 + rx) >> 3)] & (0x80 >> ((x0 + rx) & 7))) !== 0;
      if (!ink) continue;
      const idx = ry * rowBytes + (rx >> 3), mask = 0x80 >> (rx & 7);
      if (INK_IS_ZERO) data[idx] &= ~mask; else data[idx] |= mask;
    }
    out.push(...asciiBytes(`BITMAP ${x0},${run.y0},${rowBytes},${bandH},0,`));
    for (let i = 0; i < data.length; i++) out.push(data[i]);
    out.push(...CRLF);
    bands++; inkBytes += data.length;
  }
  line("PRINT 1");
  return { bytes: Uint8Array.from(out), bands, inkBytes };
}

// ── SDK-format image stream (the REAL D520 image protocol) ───────────────────
// Extracted from the manufacturer's QY/FunPrint SDK (vendor/QY_Android_SDK.zip,
// mprinter-release.aar): the AM-243Z-BT — the D520BT-Z's OEM identity, per the
// SDK's DefaultPrinters.json (203dpi, 864-dot head) — prints an image as ONE
// full-label block through the firmware's NATIVE image engine, not the legacy
// TSPL raster compositor (which is what doubles glyphs + runs slow on fw
// V1.1.7). Decompiled source of truth:
//   jf/jf/jf/ei/vno/jf/vno/ei.java  (class pao() == "AM-243Z-BT"):
//     SIZE {wDots/8} mm,{hDots/8} mm\r\n   ← NO space after the comma
//     DIRECTION 0,0\r\n                    ← not DIRECTION 1
//     CLS\r\n
//     BITMAP 4,0,{rowBytes},{hDots},4,     ← x=4, y=0, MODE 4, binary follows
//     <chunked-LZO stream>                 ← XBitmapUtil.jf(byte[]):
//         per 4096-byte raster slice: [compressedLen LE32][LZO1X-1 data]
//     00 00 00 00                          ← io/ei.java `case` = end terminator
//     \r\nPRINT 1,{copies}\n\r             ← trailing \n\r exactly (SDK quirk)
//   Raster (io/jf.java ei()): full-width rows, rowBytes = wDots/8, MSB-first,
//   bit 1 = WHITE / bit 0 = INK (same ink-is-zero polarity as classic TSPL).
//   No GAP / DENSITY / REFERENCE lines in the job — those are separate printer
//   settings commands in the SDK, not part of a print.
// LZO1X-1 comes from the `lzo1x` npm package (MIT, pure TS, zero deps); tests
// pin the stream by DECOMPRESSING it back to the exact packed raster.

const SDK_LZO_CHUNK = 4096;

// Our Bitmap buffer is bit1=ink; the printer raster is bit1=white → invert.
export function packPrinterRaster(full: FullRaster): Uint8Array {
  const out = new Uint8Array(full.rowBytes * full.h);
  for (let i = 0; i < out.length; i++) out[i] = ~full.buf[i] & 0xff;
  return out;
}

// 180° rotation, app-side (2026-09-07 field fix): the SDK job's DIRECTION 0,0
// feeds out rotated 180° vs the TEXT path's DIRECTION 1. The owner wants the
// old feed orientation, and changing DIRECTION in the SDK stream is a protocol
// risk (the SDK never sends 1 with mode 4) — so we rotate the FULL label
// raster before packing and keep the stream framing byte-identical. With
// wDots % 8 == 0 on every size, pixel index i maps to N-1-i: reverse the byte
// order, then reverse the bits inside each byte. Involution (twice = identity).
const BIT_REVERSE: Uint8Array = (() => {
  const t = new Uint8Array(256);
  for (let b = 0; b < 256; b++) {
    let r = 0;
    for (let i = 0; i < 8; i++) if (b & (1 << i)) r |= 0x80 >> i;
    t[b] = r;
  }
  return t;
})();
export function rotateRaster180(full: FullRaster): FullRaster {
  const n = full.buf.length;
  const out = new Uint8Array(n);
  for (let i = 0; i < n; i++) out[i] = BIT_REVERSE[full.buf[n - 1 - i]];
  return { buf: out, w: full.w, h: full.h, rowBytes: full.rowBytes };
}

// Header/terminator framing — byte-exact to the decompiled SDK builder.
// `direction` exists ONLY for probe 13 (does the mode-4 engine honor
// DIRECTION 1?) — production always sends the SDK's verbatim "0,0" and fixes
// orientation via rotateRaster180 instead.
export function buildSdkBitmapStream(printerRaster: Uint8Array, rowBytes: number, hDots: number, wMm: number, hMm: number, copies = 1, direction = "0,0"): { bytes: Uint8Array; chunks: number; compressedBytes: number } {
  const out: number[] = [];
  const ascii = (s: string) => { for (let i = 0; i < s.length; i++) out.push(s.charCodeAt(i) & 0xff); };
  ascii(`SIZE ${wMm} mm,${hMm} mm\r\n`);
  ascii(`DIRECTION ${direction}\r\n`);
  ascii("CLS\r\n");
  ascii(`BITMAP 4,0,${rowBytes},${hDots},4,`);
  let chunks = 0, compressedBytes = 0;
  for (let off = 0; off < printerRaster.length; off += SDK_LZO_CHUNK) {
    const slice = printerRaster.subarray(off, Math.min(off + SDK_LZO_CHUNK, printerRaster.length));
    const comp = lzo1xCompress(slice);
    const len = comp.length;
    out.push(len & 0xff, (len >> 8) & 0xff, (len >> 16) & 0xff, (len >> 24) & 0xff);
    for (let i = 0; i < comp.length; i++) out.push(comp[i]);
    chunks++; compressedBytes += len;
  }
  out.push(0, 0, 0, 0); // end-of-image terminator (SDK io/ei.java `case`)
  ascii(`\r\nPRINT 1,${copies}\n\r`);
  return { bytes: Uint8Array.from(out), chunks, compressedBytes };
}

// PRODUCTION (SDK-mode) path: payload → 1-bit raster → ONE compressed full-label
// image block. Replaces the mode-0 band emission as the default (that legacy
// compositor is the doubling + 4s-done culprit on fw V1.1.7; Labelife uses THIS
// path and is clean + fast on both boards).
export function rasterizeToSdkBitmapTspl(payload: RasterPayload, wMm: number, hMm: number, atlases: RasterAtlases): BitmapTsplResult {
  const full = renderStickerBitmap(payload, wMm, hMm, atlases);
  // 180° app-side (field fix): DIRECTION 0,0 feeds out inverted vs the old
  // TEXT stickers — rotate the whole label so the output matches the TEXT
  // path's orientation exactly. Full-label rotation (no cropping on this path).
  const printerRaster = packPrinterRaster(rotateRaster180(full));
  const r = buildSdkBitmapStream(printerRaster, full.rowBytes, full.h, wMm, hMm);
  return { bytes: r.bytes, bands: r.chunks, inkBytes: r.compressedBytes };
}

// Base64 for the native bridge (chunked, binary-safe).
export function bytesToBase64(bytes: Uint8Array): string {
  if (typeof btoa !== "function") return typeof Buffer !== "undefined" ? Buffer.from(bytes).toString("base64") : "";
  let bin = ""; const CH = 0x8000;
  for (let i = 0; i < bytes.length; i += CH) bin += String.fromCharCode.apply(null, Array.from(bytes.subarray(i, i + CH)));
  return btoa(bin);
}

// ═══════════════════════════════════════════════════════════════════════════════════════
// PROPORTIONAL (font C) compact layout — generic-printer and Niimbot IMAGE paths only.
// Opt-in: used when `atlases.proportional` is passed (printing.ts passes it on those two
// paths for the compact sizes; the D520BT SDK stream never does → byte-identical).
//   • Proportional DejaVu Sans REGULAR for Latin / digits / symbols / Cyrillic (per-glyph
//     advances; the buyer number alone is DejaVu Sans Bold), Noto Sans CJK TC REGULAR cells
//     for CJK with PROP_CJK_GAP (1 dot) after every CJK glyph so characters never touch →
//     mixed lines ("陳美玲 Amy Chen", "測試 Test Print") read normally.
//   • Lines: buyer number (big) · @username · buyer name · comment · date-time, evenly
//     spaced over the label height. The username / name / comment lines SHRINK before they
//     are cut: 50×30 lines 20 → 18 px, 60×40 lines 24 → 20 → 18 px, and "…" only if 18 still
//     overflows. The buyer number and the date-time keep their size.
//   • QR (TikTok + sticker-QR ON + @username on): label-tall on the right, 5 dots/module,
//     vertically centred, `edge` dots from the right. The text column ends BEFORE the QR's
//     quiet zone (the stamp clears that footprint, so nothing may be painted there) — i.e.
//     ≥ 20 dots before the QR's first ink column, more than PROP_TEXT_QR_GAP. No QR
//     (Facebook, or QR off): the text uses the full width and the buyer number steps up.
//   • Fit = the real INK extent of a line (advances + the last glyph's right overhang, or
//     the "…" itself) + PROP_INK_MARGIN ≤ the column — a glyph is never partially painted.
//   • 50×30 (raster 384 = the 48 mm printable width) and 60×40 (raster 480 = the label).
//   • The size choice depends on glyph ADVANCES only (CJK = one cell = the size), never on
//     which CJK atlas is loaded → propPlanCjkSizes() tells the loader which CJK sizes a
//     label needs before any CJK atlas is fetched, and the paint lands on the same sizes.
// ═══════════════════════════════════════════════════════════════════════════════════════
export interface PropGlyph { w: number; adv: number; rows: string } // rows: base64, ceil(w/8) B/row × font.h, bit 1 = ink; "" = blank (space)
export interface PropFont { h: number; base: number; glyphs: Record<number, PropGlyph> }
export type PropAtlas = Record<string, PropFont>;          // keys = px sizes ("18" "20" "24" "32" "46" "64")
export type CjkRegSize = 18 | 20 | 24 | 32;
export type CjkRegAtlases = Partial<Record<CjkRegSize, GlyphAtlas>>;
export const CJK_REG_SIZES: CjkRegSize[] = [18, 20, 24, 32];

export const isPropCompactSize = (wMm: number, hMm: number): boolean => (wMm === 50 && hMm === 30) || (wMm === 60 && hMm === 40);
export const PROP_QR_MODULE_DOTS = 5;   // 29 modules → 145-dot symbol (≈18 mm — the size the B1 scans)
export const PROP_TEXT_QR_GAP = 10;     // minimum white between the text column and the QR's first ink column (the quiet zone gives 20)
export const PROP_INK_MARGIN = 2;       // a line's painted ink (last glyph's overhang / the "…" included) ends ≥ this many dots before the column edge
export const PROP_SHRINK_STEPS = [24, 20, 18]; // the shrink ladder below a line's normal size
export const PROP_CJK_GAP = 1;          // dots of advance added after every CJK glyph (characters never touch)

interface PropSizes { num: number; line: number; time: number; edge: number }
// px sizes per label (em px of the atlas); `edge` = left/right margin in RASTER dots.
export function propSizes(wMm: number, qr: boolean): PropSizes {
  if (wMm === 50) return { num: qr ? 46 : 64, line: 20, time: 18, edge: 4 }; // 4 raster dots = 12 on the 400-dot label
  return { num: 64, line: 24, time: 20, edge: 12 };
}
/** The sizes a shrinkable line tries, biggest first: its normal size, then every step below it. */
export const propShrinkLadder = (base: number): number[] => [base, ...PROP_SHRINK_STEPS.filter((s) => s < base)];

// The label-tall right-side QR of the proportional layout (same gates as stickerQrPlacement).
export function propQrPlacement(payload: RasterPayload, wDots: number, hDots: number, edge: number): QrPlacement | null {
  if (!payload.settings || payload.settings.printStickerQr !== true) return null;
  if (payload.settings.printBuyerUsername === false) return null;
  const handle = payload.buyer?.handle ? String(payload.buyer.handle).trim() : "";
  if (!handle) return null;
  const url = tiktokProfileUrl(handle);
  if (!url) return null;
  const m = qrMatrix(url, "M");
  if (!m) return null;
  const scale = PROP_QR_MODULE_DOTS, n = m.length;
  const foot = (n + 2 * QR_QUIET_MODULES) * scale;
  if (foot > hDots) return null;
  const x0 = wDots - edge - (n + QR_QUIET_MODULES) * scale; // quiet-zone start; the symbol's ink ends `edge` dots before the right edge
  if (x0 < 0) return null;
  return { matrix: m, x0, y0: Math.max(0, Math.floor((hDots - foot) / 2)), foot, scale };
}
/** First ink column of a placed QR (its left quiet zone is white). */
export const propQrInkLeft = (qr: QrPlacement): number => qr.x0 + QR_QUIET_MODULES * qr.scale;

interface PropItem { x: number; latin?: PropGlyph; cjk?: number } // cjk = the codepoint, painted from the size's CJK atlas
export interface PropLine { items: PropItem[]; width: number; inkWidth: number; text: string; cut: boolean; cjk: boolean } // width = Σ advances; inkWidth = painted extent (last glyph's overhang included)

const isIdeograph = (cp: number) => (cp >= 0x4e00 && cp <= 0x9fff) || (cp >= 0x3400 && cp <= 0x4dbf) || (cp >= 0xf900 && cp <= 0xfaff);
function propCjkFont(atlases: RasterAtlases, size: number): GlyphFont | null {
  const reg = atlases.cjkReg?.[size as CjkRegSize];
  return reg?.cjk ?? atlases.cjk?.cjk ?? null;
}

/** Lay one line out in font `size`, cutting with "…" so it fits `maxW`. PURE; widths never
 *  depend on which CJK atlas is present (an ideograph is always one `size`-wide cell). */
export function propFitLine(text: string, size: number, maxW: number, atlases: RasterAtlases): PropLine {
  const font = atlases.proportional?.[String(size)];
  if (!font) return { items: [], width: 0, inkWidth: 0, text: "", cut: false, cjk: false };
  const cjkFont = propCjkFont(atlases, size); // only consulted for NON-ideographs the Latin font lacks (fullwidth punctuation, kana…)
  type Piece = { ch: string; adv: number; latin?: PropGlyph; cjk?: number };
  const pieces: Piece[] = [];
  for (const ch of text) {
    const cp = ch.codePointAt(0) ?? 0;
    if (isIdeograph(cp)) { pieces.push({ ch, adv: size + PROP_CJK_GAP, cjk: cp }); continue; }
    let g = font.glyphs[cp];
    if (!g) { const alt = translitCp(cp); if (alt != null) g = font.glyphs[alt]; }
    if (!g && cjkFont?.glyphs[cp]) { pieces.push({ ch, adv: cjkFont.w + PROP_CJK_GAP, cjk: cp }); continue; }
    if (!g) continue; // never tofu: a glyph neither font has is dropped
    pieces.push({ ch, adv: g.adv, latin: g });
  }
  const widthOf = (ps: Piece[]) => ps.reduce((a, p) => a + p.adv, 0);
  // painted extent: every advance but the last glyph's (CJK advances include PROP_CJK_GAP), then
  // the WIDER of the last glyph's advance and its ink box (a CJK cell's ink is the cell itself)
  const inkOf = (ps: Piece[]) => (ps.length === 0 ? 0 : widthOf(ps.slice(0, -1)) + Math.max(ps[ps.length - 1].adv, ps[ps.length - 1].latin?.rows ? ps[ps.length - 1].latin!.w : ps[ps.length - 1].adv));
  const fits = (ps: Piece[]) => inkOf(ps) + PROP_INK_MARGIN <= maxW;
  let kept = pieces;
  let suffix: Piece | null = null;
  const cut = !fits(pieces);
  if (cut) {
    const ell = font.glyphs[0x2026];
    const ellPiece: Piece | null = ell ? { ch: "…", adv: ell.adv, latin: ell } : null;
    let k = pieces.length;
    while (k > 0 && !fits(ellPiece ? [...pieces.slice(0, k), ellPiece] : pieces.slice(0, k))) k--;
    while (k > 0 && pieces[k - 1].ch === " ") k--; // no space right before the "…"
    kept = pieces.slice(0, k);
    suffix = ellPiece;
  }
  const out = suffix ? [...kept, suffix] : kept;
  const items: PropItem[] = [];
  let x = 0;
  for (const p of out) { items.push({ x, latin: p.latin, cjk: p.cjk }); x += p.adv; }
  return { items, width: x, inkWidth: inkOf(out), text: out.map((p) => p.ch).join(""), cut, cjk: out.some((p) => p.cjk != null) };
}

/** A shrinkable line: the first ladder size that fits whole, else the smallest (cut). */
export function propFitShrinking(text: string, base: number, maxW: number, atlases: RasterAtlases): { size: number; line: PropLine } | null {
  let last: { size: number; line: PropLine } | null = null;
  for (const size of propShrinkLadder(base)) {
    if (!atlases.proportional?.[String(size)]) continue;
    last = { size, line: propFitLine(text, size, maxW, atlases) };
    if (!last.line.cut) return last;
  }
  return last;
}

interface PropLaidLine { size: number; font: PropFont; line: PropLine }
/** All the label's lines with their final sizes (PURE; CJK atlases not needed). */
export function propLayoutLines(payload: RasterPayload, wMm: number, hMm: number, atlases: RasterAtlases): { lines: PropLaidLine[]; qr: QrPlacement | null; x: number; w: number; h: number } {
  const W = stickerConfig(wMm, hMm).wDots, H = hMm * 8;
  const prop = atlases.proportional;
  const buyer = payload.buyer ?? {};
  const settings = payload.settings;
  const flag = (key: keyof RasterSettings) => (settings == null ? true : settings[key] !== false);
  const orders = buyer.orders ?? [];
  const narrow = (s: string) => stripUnrenderableExt(safe(s), true).replace(/\s+/g, " ").trim();

  const qrProbe = propQrPlacement(payload, W, H, propSizes(wMm, true).edge);
  const sizes = propSizes(wMm, !!qrProbe);
  const qr = qrProbe ? propQrPlacement(payload, W, H, sizes.edge) : null;
  const X = sizes.edge;
  const right = qr ? Math.min(qr.x0, propQrInkLeft(qr) - PROP_TEXT_QR_GAP) : W - sizes.edge; // never inside the quiet zone the stamp clears
  const maxW = Math.max(1, right - X);
  if (!prop) return { lines: [], qr, x: X, w: W, h: H };

  // the lines, top → bottom (empties and switched-off fields drop out; spacing re-flows)
  const spec: { text: string; size: number; shrink: boolean }[] = [];
  const num = String(buyer.num ?? buyer.bNum ?? 0);
  if (flag("printBuyerNumber")) spec.push({ text: num, size: sizes.num, shrink: false });
  const handle = stripEmoji(buyer.handle ?? "");
  if (flag("printBuyerUsername") && handle) spec.push({ text: "@" + handle, size: sizes.line, shrink: true });
  const cleanName = stripEmoji(buyer.name ?? "");
  let nameOut = cleanName;
  if ((buyer.name ?? "") && !cleanName) nameOut = handle ? handle : `Buyer #${num}`;
  if (nameOut && classifyScriptExt(nameOut, true) === SCRIPT_UNSUPPORTED) nameOut = handle && classifyScriptExt(handle, true) === SCRIPT_ASCII ? handle : "";
  if (nameOut) spec.push({ text: nameOut, size: sizes.line, shrink: true });
  if (flag("printOrderItems") && orders.length > 0) { const c = stripEmoji(orders[0]?.item ?? ""); if (c.trim()) spec.push({ text: c, size: sizes.line, shrink: true }); }
  const date = String(payload.sessionDate ?? "").replace(/^(\d{2}\/\d{2})\/\d{4}$/, "$1");
  const time = orders[0]?.time ?? "";
  const when = [date, time].filter(Boolean).join(" ");
  if (when) spec.push({ text: when, size: sizes.time, shrink: false });

  const lines: PropLaidLine[] = [];
  for (const l of spec) {
    const t = narrow(l.text);
    if (!t) continue;
    const fit = l.shrink ? propFitShrinking(t, l.size, maxW, atlases) : (prop[String(l.size)] ? { size: l.size, line: propFitLine(t, l.size, maxW, atlases) } : null);
    if (!fit || !fit.line.text) continue;
    lines.push({ size: fit.size, font: prop[String(fit.size)], line: fit.line });
  }
  return { lines, qr, x: X, w: W, h: H };
}

/** The CJK atlas sizes this label will paint with (for the loader — before any CJK atlas is fetched). */
export function propPlanCjkSizes(payload: RasterPayload, wMm: number, hMm: number, prop: PropAtlas): CjkRegSize[] {
  const { lines } = propLayoutLines(payload, wMm, hMm, { latin: {}, proportional: prop });
  const sizes = new Set<CjkRegSize>();
  for (const l of lines) if (l.line.cjk && (CJK_REG_SIZES as number[]).includes(l.size)) sizes.add(l.size as CjkRegSize);
  return CJK_REG_SIZES.filter((s) => sizes.has(s));
}

/** The top row of every line: evenly spaced over the height (PURE, shared with the tests). */
export function propLineTops(lines: { font: PropFont }[], h: number): number[] {
  const total = lines.reduce((a, l) => a + l.font.h, 0);
  const gap = Math.max(0, Math.floor((h - total) / (lines.length + 1)));
  const tops: number[] = [];
  let y = gap;
  for (const l of lines) { tops.push(y); y += l.font.h + gap; }
  return tops;
}
/** Where one item's glyph is painted (x, top, w, h) — PURE, shared with the glyph-integrity tests. */
export function propGlyphBox(item: PropItem, size: number, x0: number, top: number, font: PropFont, atlases: RasterAtlases): { x: number; y: number; w: number; h: number; cell: Uint8Array } | null {
  if (item.latin) return item.latin.rows ? { x: x0 + item.x, y: top, w: item.latin.w, h: font.h, cell: b64ToBytes(item.latin.rows) } : null;
  if (item.cjk == null) return null;
  const cjkFont = propCjkFont(atlases, size);
  const g = cjkFont?.glyphs[item.cjk];
  if (!g || !cjkFont) return null;
  return { x: x0 + item.x + Math.max(0, Math.round((size - cjkFont.w) / 2)), y: top + Math.round((font.h - cjkFont.h) / 2), w: cjkFont.w, h: cjkFont.h, cell: b64ToBytes(g) };
}

/** The whole compact label as a 1-bit bitmap (the only painter of the font-C layout). */
export function renderPropCompact(payload: RasterPayload, wMm: number, hMm: number, atlases: RasterAtlases): Bitmap {
  const { lines, qr, x, w, h } = propLayoutLines(payload, wMm, hMm, atlases);
  const bmp = new Bitmap(w, h);
  const tops = propLineTops(lines, h);
  lines.forEach((l, i) => { for (const it of l.line.items) { const b = propGlyphBox(it, l.size, x, tops[i], l.font, atlases); if (b) bmp.blit(b.cell, b.w, b.h, b.x, b.y, 1, 1); } });
  stampHandleQr(bmp, qr);
  return bmp;
}
