// Bitmap sticker path — shared TS rasterizer (Phase 1, Android dev-verify).
//
// WHY: the new-board D520BT (fw V1.1.7) DOUBLES every ROM font glyph, so the TEXT
// path (TsplBuilder.java / Swift buildTsplSticker / tsplReference.ts) prints garbled
// on those units. Both boards print a TSPL BITMAP raster block CLEAN. So we render
// the WHOLE sticker to a 1-bit raster in TS and send it via BITMAP — clean on the
// new board, identical layout to the old TEXT sticker.
//
// ARCHITECTURE (parity by construction):
//   stickerDrawOps()          — the LAYOUT, mirrored op-for-op from the frozen
//                               tsplReference.ts. THE single source of positions.
//   emitTextTspl(ops)         — serializes ops back into the exact TEXT/BAR stream.
//                               TEST-ONLY: proves emitTextTspl == the frozen
//                               reference byte-for-byte (layout fidelity guard).
//   rasterizeToBitmapTspl()   — the PRODUCTION path: ops → 1-bit buffer (glyph
//                               blit) → ink-band crop → BITMAP blocks → TSPL.
//
// The frozen TEXT builders/goldens are NEVER imported or modified here; the layout
// is re-derived and pinned by the parity test.
//
// Glyphs come from committed 1-bit atlases (glyphAtlas.latin.ts + glyphAtlas.cjk.ts,
// generated by scripts/gen-glyph-atlas.mjs). Runtime never rasterizes a font →
// deterministic goldens. Cells match the printer's built-in font boxes:
//   font "2" 12x20 · "3" 16x24 · "4" 24x32 · CJK "TSS24" 24x24.

// ── Atlas shape (produced by the generator) ─────────────────────────────────
export interface GlyphFont { w: number; h: number; glyphs: { [cp: number]: string } } // base64 rows, MSB-first, ceil(w/8) B/row x h
export interface GlyphAtlas { [fontKey: string]: GlyphFont }

// TSPL BITMAP polarity. TSPL standard + the owner's probe photo (black bar at the
// 0x00 top half) => an INK dot is bit 0, white is bit 1. Single flip point.
export const INK_IS_ZERO = true;

// ── Pure helpers — mirrors of tsplReference.ts / TsplBuilder.java (parity-tested) ──
const CRLF = [0x0d, 0x0a];
function asciiBytes(s: string): number[] {
  const out: number[] = [];
  for (let i = 0; i < s.length; i++) { const c = s.charCodeAt(i); out.push(c <= 127 ? c : 0x3f); }
  return out;
}
function truncate(s: string, maxLen: number): string { return s.length > maxLen ? s.slice(0, maxLen) : s; }
function safe(s: string): string { return s.replace(/"/g, "'"); }
function hasNonAscii(s: string): boolean { for (let i = 0; i < s.length; i++) if (s.charCodeAt(i) > 127) return true; return false; }
function isStrippable(cp: number): boolean {
  return cp >= 0x1f000 || (cp >= 0x2600 && cp <= 0x27bf) || (cp >= 0xfe00 && cp <= 0xfe0f) || cp === 0x200d || cp === 0x20e3;
}
function javaTrim(s: string): string {
  let a = 0, b = s.length;
  while (a < b && s.charCodeAt(a) <= 0x20) a++;
  while (b > a && s.charCodeAt(b - 1) <= 0x20) b--;
  return s.slice(a, b);
}
function stripEmoji(s: string): string {
  if (!s) return "";
  let kept = "";
  for (const ch of s) if (!isStrippable(ch.codePointAt(0) ?? 0)) kept += ch;
  return javaTrim(kept);
}
function money(v: number): string { return v === Math.trunc(v) ? String(v) : v.toFixed(2); }
const SCRIPT_ASCII = 1, SCRIPT_CJK = 2, SCRIPT_UNSUPPORTED = 3;
const ATOMIC_LATIN: Record<string, string> = {
  "đ": "d", "Đ": "D", "ł": "l", "Ł": "L", "ø": "o", "Ø": "O", "æ": "ae", "Æ": "AE",
  "œ": "oe", "Œ": "OE", "ß": "ss", "þ": "th", "Þ": "Th", "ð": "d", "Ð": "D", "ı": "i",
};
function transliterateLatin(s: string): string {
  if (!s) return "";
  let out = "";
  for (const ch of s.normalize("NFD")) {
    const cp = ch.codePointAt(0) ?? 0;
    if (cp >= 0x300 && cp <= 0x36f) continue;
    out += ATOMIC_LATIN[ch] ?? ch;
  }
  return out;
}
function isCjkIdeograph(cp: number): boolean {
  return (cp >= 0x4e00 && cp <= 0x9fff) || (cp >= 0x3400 && cp <= 0x4dbf) || (cp >= 0xf900 && cp <= 0xfaff);
}
function classifyScript(s: string): number {
  let hasCjk = false;
  for (const ch of s) {
    const cp = ch.codePointAt(0) ?? 0;
    if (cp <= 127) continue;
    if (isCjkIdeograph(cp)) { hasCjk = true; continue; }
    return SCRIPT_UNSUPPORTED;
  }
  return hasCjk ? SCRIPT_CJK : SCRIPT_ASCII;
}
function stripUnrenderable(s: string): string {
  let out = "";
  for (const ch of s) { const cp = ch.codePointAt(0) ?? 0; if (cp <= 127 || isCjkIdeograph(cp)) out += ch; }
  return out;
}

